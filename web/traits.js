const descriptions = new Map(traitGroups.flatMap(group => group.traits));
const canonicalLabels = new Map();
for (const {traits} of traitGroups) {
  for (const [label,,...oldLabels] of traits) {
    for (const name of [label,...oldLabels]) canonicalLabels.set(name,label);
  }
}

export function describePersonality(note, selected) {
  const custom = note.trim();
  const labels = [...new Set(selected.map(label => canonicalLabels.get(label)))];
  const sentences = labels.map(label => descriptions.get(label))
    .filter(sentence => sentence && !custom.includes(sentence));
  return [custom, ...sentences].filter(Boolean).join(' ');
}

export function mountTraitPicker(onChange) {
  const tabList = document.getElementById('traitTabs');
  const panels = document.getElementById('traitPanels');
  const chosen = document.getElementById('chosenTraits');
  const count = document.getElementById('traitCount');
  const selected = new Set();
  const buttons = new Map();
  const tabs = [];
  let active = 0;

  function showGroup(index) {
    active = index;
    tabs.forEach((tab,i) => {
      tab.tabIndex = i === index ? 0 : -1;
      tab.setAttribute('aria-selected',String(i === index));
      panels.children[i].hidden = i !== index;
    });
  }

  function paintSelection() {
    for (const [label,button] of buttons) {
      button.setAttribute('aria-pressed',String(selected.has(label)));
    }
    count.textContent = '고른 행동 '+selected.size+'개';
    chosen.replaceChildren(...Array.from(selected, label => {
      const remove = document.createElement('button');
      remove.type = 'button';
      remove.dataset.remove = label;
      remove.textContent = label;
      remove.setAttribute('aria-label',label+' 선택 해제');
      return remove;
    }));
  }

  traitGroups.forEach(({name,traits},i) => {
    const tab = document.createElement('button');
    tab.type = 'button';
    tab.id = 'trait-tab-'+i;
    tab.setAttribute('role','tab');
    tab.setAttribute('aria-controls','trait-panel-'+i);
    tab.textContent = name;
    tab.addEventListener('click',() => showGroup(i));
    tab.addEventListener('keydown',event => {
      const last = tabs.length-1;
      const next = {ArrowLeft:(i+last)%tabs.length, ArrowRight:(i+1)%tabs.length, Home:0, End:last}[event.key];
      if (next === undefined) return;
      event.preventDefault();
      showGroup(next);
      tabs[next].focus();
    });
    tabs.push(tab);
    tabList.append(tab);

    const panel = document.createElement('div');
    panel.className = 'trait-options';
    panel.id = 'trait-panel-'+i;
    panel.setAttribute('role','tabpanel');
    panel.setAttribute('aria-labelledby',tab.id);
    for (const [label,sentence] of traits) {
      const button = document.createElement('button');
      button.type = 'button';
      button.dataset.trait = label;
      button.textContent = label;
      button.title = sentence;
      button.setAttribute('aria-label',label);
      button.setAttribute('aria-description',sentence);
      buttons.set(label,button);
      panel.append(button);
    }
    panels.append(panel);
  });

  panels.addEventListener('click',event => {
    const button = event.target.closest('button[data-trait]');
    if (!button) return;
    const label = button.dataset.trait;
    if (selected.has(label)) selected.delete(label);
    else selected.add(label);
    paintSelection();
    onChange();
  });
  chosen.addEventListener('click',event => {
    const remove = event.target.closest('button[data-remove]');
    if (!remove) return;
    const position = [...chosen.children].indexOf(remove);
    selected.delete(remove.dataset.remove);
    paintSelection();
    const remaining = chosen.children;
    const option = buttons.get(remove.dataset.remove);
    const fallback = option.closest('[role="tabpanel"]').hidden ? tabs[active] : option;
    (remaining[Math.min(position,remaining.length-1)] || fallback).focus();
    onChange();
  });

  function restore(labels = []) {
    selected.clear();
    for (const name of labels) {
      const label = canonicalLabels.get(name);
      if (label) selected.add(label);
    }
    paintSelection();
    showGroup(0);
  }
  restore();
  return {selected:() => [...selected], restore};
}
